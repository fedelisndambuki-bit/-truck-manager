<?php

namespace App\Observers;

use App\Models\Maintenance;
use App\Enums\TruckStatus;

class MaintenanceObserver
{
    /**
     * Handle the Maintenance "created" event.
     */
    public function created(Maintenance $maintenance): void
    {
        $this->updateTruckStatus($maintenance);
        $this->updateTruckMileage($maintenance);
        $this->postEquipmentCost($maintenance);
    }

    /**
     * Handle the Maintenance "updated" event.
     */
    public function updated(Maintenance $maintenance): void
    {
        $this->updateTruckStatus($maintenance);
        $this->updateTruckMileage($maintenance);
        $this->postEquipmentCost($maintenance);
        $this->syncExpense($maintenance);
    }

    /**
     * Equipment & Asset Management cost posting — runs independently of
     * updateTruckStatus() (which exits early when there's no linked truck)
     * so it also fires for equipment-only maintenance records with no
     * truck_id, e.g. every Maintenance row generated by closing a
     * MaintenanceWorkOrder.
     */
    protected function postEquipmentCost(Maintenance $maintenance): void
    {
        if (! $maintenance->equipment_id || $maintenance->status !== 'Completed' || (float) $maintenance->cost <= 0) {
            return;
        }

        $exists = \App\Models\EquipmentCostEntry::where('source_type', Maintenance::class)
            ->where('source_id', $maintenance->id)
            ->exists();

        if ($exists) {
            return;
        }

        \App\Models\EquipmentCostEntry::create([
            'company_id' => $maintenance->company_id,
            'equipment_id' => $maintenance->equipment_id,
            'cost_category' => 'Maintenance',
            'amount' => $maintenance->cost,
            'incurred_on' => $maintenance->maintenance_date ?: now()->toDateString(),
            'source_type' => Maintenance::class,
            'source_id' => $maintenance->id,
            'description' => $maintenance->workOrder
                ? "Work order {$maintenance->workOrder->work_order_number} closed"
                : "Maintenance #{$maintenance->id}: {$maintenance->maintenance_type}",
        ]);

        // When a truck is also linked, createExpense() (called from
        // updateTruckStatus()) already posts this cost to the GL via
        // ExpenseObserver — posting again here would double-book it.
        if ($maintenance->truck_id) {
            return;
        }

        try {
            app(\App\Services\PostingEngineService::class)->post('maintenance.equipment_cost', [
                'company_id' => $maintenance->company_id,
                'reference_type' => 'maintenance',
                'reference_id' => (string) $maintenance->id,
                'amount' => (float) $maintenance->cost,
                'description' => "Equipment maintenance — {$maintenance->equipment?->name}",
            ]);
        } catch (\Exception $e) {
            \Illuminate\Support\Facades\Log::error("Failed to post maintenance cost to ledger: " . $e->getMessage());
        }
    }

    /**
     * Update truck status based on maintenance status.
     */
    protected function updateTruckStatus(Maintenance $maintenance): void
    {
        $truck = $maintenance->truck;
        if (!$truck) return;

        if ($maintenance->status === 'Pending') {
            $truck->status = TruckStatus::UnderMaintenance;
            $truck->save();
        } elseif ($maintenance->status === 'Completed') {
            // Record as Expense if cost > 0
            if ($maintenance->cost > 0) {
                $this->createExpense($maintenance);
            }

            // Only set to Available if it was Under Maintenance
            if ($truck->status === TruckStatus::UnderMaintenance) {
                $truck->status = TruckStatus::Available;
                $truck->save();
            }
        }
    }

    protected function createExpense(Maintenance $maintenance): void
    {
        // Exact FK match — the previous `description LIKE '%Maintenance
        // #{id}%'` dedup was ambiguous across ids sharing a prefix (e.g.
        // #1 matches #17), silently swallowing real repair expenses.
        if (\App\Models\Expense::where('maintenance_id', $maintenance->id)->exists()) {
            return;
        }

        \App\Models\Expense::create([
            'company_id' => $maintenance->company_id ?: 1,
            'truck_id' => $maintenance->truck_id,
            'maintenance_id' => $maintenance->id,
            'category' => 'Repair',
            'amount' => $maintenance->cost,
            'date' => $maintenance->maintenance_date ?: now(),
            'payment_method' => 'Bank Transfer', // Default for maintenance
            'description' => "Maintenance #{$maintenance->id}: {$maintenance->maintenance_type}. Provider: {$maintenance->service_provider}"
        ]);
    }

    /**
     * Correcting the cost on an already-Completed maintenance used to never
     * reach its Expense/GL entry at all (createExpense()'s dedup just
     * skipped it) — sync the amount instead, matching
     * FuelLogObserver::syncExpense().
     */
    protected function syncExpense(Maintenance $maintenance): void
    {
        if ($maintenance->status !== 'Completed' || (float) $maintenance->cost <= 0) {
            return;
        }

        $expense = \App\Models\Expense::where('maintenance_id', $maintenance->id)->first();
        if (! $expense) return;

        $expense->update(['amount' => $maintenance->cost]);
    }

    /**
     * Update truck mileage if the maintenance record has a higher mileage.
     */
    protected function updateTruckMileage(Maintenance $maintenance): void
    {
        $truck = $maintenance->truck;
        if (!$truck) return;

        if ($maintenance->mileage_at_service > ($truck->current_mileage ?? 0)) {
            $truck->current_mileage = $maintenance->mileage_at_service;
            $truck->save();
        }
    }
}
