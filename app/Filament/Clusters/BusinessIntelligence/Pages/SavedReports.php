<?php

namespace App\Filament\Clusters\BusinessIntelligence\Pages;

use App\Filament\Clusters\BusinessIntelligence;
use App\Models\ReportExport;
use App\Traits\HasModuleAccess;
use Filament\Pages\Page;
use Filament\Tables;
use Filament\Tables\Concerns\InteractsWithTable;
use Filament\Tables\Contracts\HasTable;
use Filament\Tables\Table;
use Illuminate\Support\Facades\Auth;

class SavedReports extends Page implements HasTable
{
    use HasModuleAccess;
    use InteractsWithTable;

    public static function getModuleSlug(): ?string
    {
        return 'bi.view';
    }

    protected static ?string $cluster = BusinessIntelligence::class;

    protected static ?string $navigationIcon = 'heroicon-o-archive-box';

    protected static ?string $navigationLabel = 'Saved Reports';

    protected static ?int $navigationSort = 15;

    protected static ?string $title = 'Saved Reports';

    protected static string $view = 'filament.clusters.business-intelligence.pages.saved-reports';

    public function table(Table $table): Table
    {
        $companyId = Auth::user()?->company_id;

        return $table
            ->query(
                ReportExport::query()
                    ->when($companyId, fn ($q) => $q->where('company_id', $companyId))
                    ->with(['generatedBy', 'project'])
                    ->latest()
            )
            ->columns([
                Tables\Columns\TextColumn::make('report_name')->searchable()->sortable()->weight('semibold'),
                Tables\Columns\TextColumn::make('report_type')->badge()->color('gray')->toggleable(),
                Tables\Columns\TextColumn::make('format')->badge()->color('info'),
                Tables\Columns\TextColumn::make('project.name')->label('Project')->placeholder('Company-wide')->toggleable(),
                Tables\Columns\TextColumn::make('generatedBy.name')->label('Generated By'),
                Tables\Columns\TextColumn::make('file_size_for_humans')->label('Size'),
                Tables\Columns\TextColumn::make('created_at')->dateTime()->sortable()->label('Generated At'),
            ])
            ->filters([
                Tables\Filters\SelectFilter::make('format')->options([
                    'pdf' => 'PDF', 'csv' => 'CSV', 'excel' => 'Excel', 'word' => 'Word', 'json' => 'JSON',
                ]),
            ])
            ->defaultSort('created_at', 'desc')
            ->paginated([10, 25, 50])
            ->striped();
    }
}
