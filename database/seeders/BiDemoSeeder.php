<?php

namespace Database\Seeders;

use App\Filament\Clusters\BusinessIntelligence\Pages\KpiDashboard;
use App\Models\BiDashboardWidget;
use App\Models\Company;
use App\Models\CustomReport;
use App\Models\Project;
use App\Models\QualityInspection;
use App\Models\QualityIssue;
use App\Models\ScheduledReport;
use App\Models\Site;
use App\Models\Staff;
use App\Models\User;
use App\Services\Construction\AiInsightsService;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\DB;

/**
 * Realistic Reports & Business Intelligence demo data for the existing
 * construction demo company (see ConstructionDemoSeeder / ProjectFinanceDemoSeeder
 * / DocumentManagementDemoSeeder). Idempotent — bails if quality issues already
 * exist for this company. AI Insights are generated by actually running
 * AiInsightsService against the real seeded Finance/Safety/Quality data, not
 * fabricated.
 */
class BiDemoSeeder extends Seeder
{
    public function run(): void
    {
        $company = Company::find(15);

        if (! $company || $company->industry !== 'construction') {
            $this->command?->warn('Skipping BiDemoSeeder: demo construction company (id 15) not found.');

            return;
        }

        if (QualityIssue::withoutGlobalScope('company')->where('company_id', 15)->exists()) {
            $this->command?->info('BiDemoSeeder: data already exists, skipping.');

            return;
        }

        DB::transaction(function () use ($company) {
            $companyId = $company->id;
            $projects = Project::withoutGlobalScope('company')->where('company_id', $companyId)->get();
            $sites = Site::withoutGlobalScope('company')->where('company_id', $companyId)->get();
            $staff = Staff::withoutGlobalScope('company')->where('company_id', $companyId)->get();
            $inspections = QualityInspection::withoutGlobalScope('company')->where('company_id', $companyId)->get();
            $user = User::withoutGlobalScope('company')->where('company_id', $companyId)->first();

            $this->seedQualityIssues($companyId, $projects, $sites, $staff, $inspections);
            $this->seedCustomReport($companyId, $user);
            $this->seedScheduledReport($companyId, $user);
            $this->seedAiInsights($companyId);
            $this->seedDashboardWidgets($user);
        });

        $this->command?->info('BiDemoSeeder: seeded quality issues, a custom report, a scheduled report, AI insights, and KPI dashboard defaults.');
    }

    protected function seedQualityIssues($companyId, $projects, $sites, $staff, $inspections): void
    {
        $failedInspection = $inspections->firstWhere('result', 'Fail');
        $project = $projects->first();
        $site = $sites->first();
        $raisedBy = $staff->first();
        $assignedTo = $staff->skip(1)->first() ?? $staff->first();

        $defs = [
            ['type' => 'NCR', 'title' => 'Concrete cover deficiency on Level 3 slab', 'severity' => 'High', 'status' => 'Open'],
            ['type' => 'NCR', 'title' => 'Incorrect rebar spacing in column C12', 'severity' => 'Medium', 'status' => 'Closed'],
            ['type' => 'CAPA', 'title' => 'Retraining of formwork crew on tolerances', 'severity' => 'Medium', 'status' => 'In Progress'],
            ['type' => 'CAPA', 'title' => 'Revise concrete pour checklist', 'severity' => 'Low', 'status' => 'Closed'],
            ['type' => 'Defect', 'title' => 'Water ponding on podium slab', 'severity' => 'Medium', 'status' => 'Open'],
            ['type' => 'Defect', 'title' => 'Cracking on block wall, Unit 4B', 'severity' => 'Low', 'status' => 'Open'],
            ['type' => 'Punch List', 'title' => 'Paint touch-up, corridor Level 2', 'severity' => 'Low', 'status' => 'Open'],
            ['type' => 'Punch List', 'title' => 'Door hardware misaligned, Unit 12', 'severity' => 'Low', 'status' => 'Closed'],
        ];

        foreach ($defs as $def) {
            $issue = QualityIssue::create([
                'company_id' => $companyId,
                'type' => $def['type'],
                'project_id' => $project?->id,
                'site_id' => $site?->id,
                'quality_inspection_id' => $failedInspection?->id,
                'title' => $def['title'],
                'description' => $def['title'] . ' — identified during routine site inspection.',
                'severity' => $def['severity'],
                'status' => $def['status'],
                'raised_by_id' => $raisedBy?->id,
                'assigned_to_id' => $assignedTo?->id,
                'due_date' => now()->addDays(14),
            ]);

            if ($def['status'] === 'Closed') {
                $issue->close();
            }
        }
    }

    protected function seedCustomReport($companyId, ?User $user): void
    {
        CustomReport::create([
            'company_id' => $companyId,
            'name' => 'Active Projects by Contract Value',
            'data_source' => 'Projects',
            'fields' => ['name', 'status', 'contract_value', 'progress_percent'],
            'filters' => [['field' => 'status', 'operator' => '=', 'value' => 'Active']],
            'group_by' => null,
            'aggregate_function' => null,
            'sort_by' => 'contract_value',
            'sort_direction' => 'desc',
            'chart_type' => 'bar',
            'created_by_id' => $user?->id,
        ]);
    }

    protected function seedScheduledReport($companyId, ?User $user): void
    {
        ScheduledReport::create([
            'company_id' => $companyId,
            'name' => 'Weekly Executive KPI Snapshot',
            'source_type' => 'existing_report',
            'source_key' => 'Executive KPI Snapshot',
            'frequency' => 'Weekly',
            'delivery_method' => 'Email',
            'format' => 'pdf',
            'recipients' => [$user?->email ?? 'construction@gmail.com'],
            'is_active' => true,
        ]);
    }

    protected function seedAiInsights($companyId): void
    {
        app(AiInsightsService::class)->generate($companyId);
    }

    protected function seedDashboardWidgets(?User $user): void
    {
        if (! $user) {
            return;
        }

        $order = 0;
        foreach (array_keys(KpiDashboard::catalog()) as $key) {
            BiDashboardWidget::firstOrCreate(
                ['user_id' => $user->id, 'widget_key' => $key],
                ['company_id' => $user->company_id, 'sort_order' => $order, 'is_visible' => true]
            );
            $order++;
        }
    }
}
